
from legacy_training_guard import require_trusted_training_adapter
require_trusted_training_adapter()

# -*- coding: utf-8 -*-
import pickle, json, os, datetime
import numpy as np

BASE = os.path.dirname(os.path.abspath(__file__))
PKL = os.path.join(BASE, 'SubModel_Policy_minimal_clean.pkl')
OUT = os.path.join(BASE, 'client_policy_model.js')

with open(PKL, 'rb') as f:
    pkg = pickle.load(f)
model = pkg['model']
classes = list(pkg['classes'])
keep = list(pkg['feature_keep'])
booster = model.booster_
dump = booster.dump_model()
trees_dump = dump['tree_info']
num_class = len(classes)

def compact_node(node):
    if 'leaf_value' in node:
        return float(node['leaf_value'])
    return [
        int(node['split_feature']),
        float(node['threshold']),
        bool(node.get('default_left', True)),
        compact_node(node['left_child']),
        compact_node(node['right_child']),
    ]

trees = []
for idx, tree in enumerate(trees_dump):
    trees.append({
        'c': idx % num_class,
        't': compact_node(tree['tree_structure']),
    })

meta = {
    'format': 'client-policy-model-v1',
    'generatedAt': datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
    'featureDim': len(keep),
    'sourceModel': 'SubModel_Policy_minimal_clean.pkl',
    'classes': classes,
    'featureKeep': keep,
    'numBoostersPerClass': len(trees_dump) // num_class,
    'trees': trees,
}

js = '''/* -*- coding: utf-8 -*-
 * client_policy_model.js
 * Pure JavaScript LightGBM multiclass export. No runtime dependency.
 * Generated by Export_Client_Policy_JS.py
 */
var CLIENT_POLICY_MODEL = __DATA__;

(function (root, factory) {
  if (typeof module !== 'undefined' && module.exports) module.exports = factory();
  else root.CLIENT_POLICY_MODEL = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  var model = CLIENT_POLICY_MODEL;

  function evalNode(node, x) {
    if (typeof node === 'number') return node;
    var feature = node[0];
    var threshold = node[1];
    var defaultLeft = node[2];
    var value = x[feature];
    var goLeft;
    if (value === null || value === undefined || isNaN(value)) goLeft = defaultLeft;
    else goLeft = value <= threshold;
    return evalNode(goLeft ? node[3] : node[4], x);
  }

  function softmax(values) {
    var max = Math.max.apply(null, values);
    var exps = values.map(function (v) { return Math.exp(v - max); });
    var sum = exps.reduce(function (a, b) { return a + b; }, 0);
    return exps.map(function (v) { return v / sum; });
  }

  model.rawScores = function (features) {
    var scores = model.classes.map(function () { return 0; });
    for (var i = 0; i < model.trees.length; i++) {
      var tree = model.trees[i];
      scores[tree.c] += evalNode(tree.t, features);
    }
    return scores;
  };

  model.predictProba = function (features) {
    return softmax(model.rawScores(features));
  };

  model.topK = function (features, k) {
    var probs = model.predictProba(features);
    return probs.map(function (prob, index) {
      return { action: model.classes[index], probability: prob };
    }).sort(function (a, b) {
      return b.probability - a.probability;
    }).slice(0, k || 3);
  };

  model.selfTest = function () {
    var zero = [];
    for (var i = 0; i < model.featureDim; i++) zero.push(0);
    var probs = model.predictProba(zero);
    var ok = Math.abs(probs.reduce(function (a, b) { return a + b; }, 0) - 1) < 1e-9 &&
             model.trees.length === model.numBoostersPerClass * model.classes.length;
    return { ok: ok, msg: 'client policy model selfTest', data: { top3: model.topK(zero, 3) } };
  };

  return model;
});
'''
js = js.replace('__DATA__', json.dumps(meta, ensure_ascii=False, separators=(',', ':')))
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(js)
print('written:', OUT)
print('size_bytes:', os.path.getsize(OUT))
print('classes:', len(classes), classes)
print('trees:', len(trees), 'per_class:', len(trees)//num_class)
